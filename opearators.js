
// What is an Operator?
// An operator performs an operation on one or more values (operands).
  
// Types of Operators in JavaScript
// Arithmetic
let a = 10;
let b = 3;

console.log(a + b);  // 13
console.log(a - b);  // 7
console.log(a * b);  // 30
console.log(a / b);  // 3.33
console.log(a % b);  // 1
console.log(a ** 2); // 100


//Assignment Operators
let x = 10;
x += 5;
console.log(x); // 15

//Comparison Operators

console.log(5 == "5");  // true  ❌
console.log(5 === "5"); // false ✅

